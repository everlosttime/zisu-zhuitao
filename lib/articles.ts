function seededShuffle<T>(items: T[], seed: number) {
  let state = seed >>> 0;
  const shuffled = [...items];
  const random = () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 2 ** 32;
  };
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const target = Math.floor(random() * (index + 1));
    [shuffled[index], shuffled[target]] = [shuffled[target], shuffled[index]];
  }
  return shuffled;
}

export const ARTICLES = Array.from({ length: 30 }, (_, articleIndex) =>
  seededShuffle(SENTENCES, articleIndex + 1).slice(0, 45).join(""),
);

export function nextArticleIndex(currentIndex: number) {
  return (currentIndex + 1) % ARTICLES.length;
}
